"""Generate the NASM file that embeds user programs in the kernel image.

  gen_user_images.py -o user_images.asm name=path.elf ...

Emits the bytes (16-byte aligned) and a table matching struct raw_image in
kernel/proc/process.c: { const char *name; const u8 *start; u64 size; }.
"""

import argparse
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", type=Path, required=True)
    ap.add_argument("images", nargs="+", help="name=path")
    args = ap.parse_args()

    entries = [tuple(spec.split("=", 1)) for spec in args.images]
    out = ["; Generated by tools/gen_user_images.py. Do not edit.", "bits 64",
           "section .rodata", "align 16"]
    for i, (name, path) in enumerate(entries):
        resolved = Path(path).resolve()
        out += [f"img{i}:", f'    incbin "{resolved}"', f"img{i}_end:", "align 16"]
    for i, (name, _) in enumerate(entries):
        out.append(f'name{i}: db "{name}", 0')
    out += ["align 8", "global user_images", "user_images:"]
    for i in range(len(entries)):
        out.append(f"    dq name{i}, img{i}, img{i}_end - img{i}")
    out += ["global user_images_count", f"user_images_count: dq {len(entries)}",
            "section .note.GNU-stack noalloc noexec nowrite progbits"]
    args.output.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
