"""Generate the kernel symbol table (kernel/core/ksyms.c reads it).

  gen_ksyms.py --empty -o ksyms.c            table for the first link pass
  gen_ksyms.py kernel.pass1.elf -o ksyms.c   real table from pass-1 symbols
  gen_ksyms.py --check kernel.elf ksyms.c    verify the final link: every
                                             function kept its address

The table only lists text symbols, and it is emitted into .rodata, which
the linker script places after .text. Adding it therefore cannot move any
function, and two passes always converge; --check proves it.
"""

import argparse
import subprocess
import sys
from pathlib import Path

HEADER = "/* Generated by tools/gen_ksyms.py. Do not edit. */\n#include <types.h>\n\n"


def text_symbols(elf: Path) -> list[tuple[int, str]]:
    out = subprocess.run(["llvm-nm", "--defined-only", "-n", str(elf)], check=True,
                         capture_output=True, text=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3 or parts[1] not in "tT":
            continue
        addr, name = int(parts[0], 16), parts[2]
        if name.startswith(".L") or name.startswith("$"):
            continue
        # Several names at one address: prefer a real function over a
        # linker-script marker such as __kernel_start or __text_start.
        current = syms.get(addr)
        if current is None or (current.startswith("__") and not name.startswith("__")):
            syms[addr] = name
    return sorted(syms.items())


def render(symbols: list[tuple[int, str]]) -> str:
    names, offsets, pos = [], [], 0
    for _, name in symbols:
        offsets.append(pos)
        names.append(name)
        pos += len(name) + 1
    blob = "".join(f"{n}\\0" for n in names)
    addrs = ",\n".join(f"    {a:#x}ul" for a, _ in symbols) or "    0"
    offs = ",\n".join(f"    {o}" for o in offsets) or "    0"
    return (HEADER
            + f"const u32 ksyms_count = {len(symbols)};\n"
            + f"const uptr ksyms_addrs[] = {{\n{addrs}\n}};\n"
            + f"const u32 ksyms_name_offsets[] = {{\n{offs}\n}};\n"
            + f"const char ksyms_names[] = \"{blob}\";\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--empty", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("inputs", nargs="*", type=Path)
    ap.add_argument("-o", "--output", type=Path)
    args = ap.parse_args()

    if args.check:
        elf, table = args.inputs
        if render(text_symbols(elf)) != table.read_text():
            print(f"gen_ksyms: {elf}: symbol addresses moved between link passes",
                  file=sys.stderr)
            return 1
        return 0

    symbols = [] if args.empty else text_symbols(args.inputs[0])
    # Always write: make decides when this runs, and an output left older than
    # its inputs would be regenerated on every build.
    args.output.write_text(render(symbols))
    return 0


if __name__ == "__main__":
    sys.exit(main())
